VDOT_MIN_DURATION_S = 90          # короче — формула Дэниелса не откалибрована (спринт)
VDOT_MAX_DURATION_S = 90 * 60     # длиннее 1.5ч — берём как есть, но с осторожностью
VDOT_MIN_PLAUSIBLE = 20.0
VDOT_MAX_PLAUSIBLE = 85.0
VDOT_ROLLING_WINDOW_D = 45


def vdot_from_effort(distance_m, duration_s):
    """VDOT (Daniels' Running Formula) по одному непрерывному быстрому усилию — см. п.1
    докстринга модуля. Возвращает None, если исходных данных недостаточно или результат
    физиологически неправдоподобен (скорее всего GPS/пульсовая погрешность)."""
    if not distance_m or not duration_s or duration_s <= 0:
        return None
    if duration_s < VDOT_MIN_DURATION_S or duration_s > VDOT_MAX_DURATION_S:
        return None
    t_min = duration_s / 60.0
    v = distance_m / t_min
    vo2 = -4.60 + 0.182258 * v + 0.000104 * v ** 2
    pct = 0.8 + 0.1894393 * np.exp(-0.012778 * t_min) + 0.2989558 * np.exp(-0.1932605 * t_min)
    if pct <= 0 or vo2 <= 0:
        return None
    vdot = vo2 / pct
    if not (VDOT_MIN_PLAUSIBLE <= vdot <= VDOT_MAX_PLAUSIBLE):
        return None
    return round(float(vdot), 2)


def load_active_laps(db_path):
    """Work-лапы (LAP_ACTIVE_TYPES) с датой и type_guess родительской активности —
    источник VDOT для type_guess=='interval' (см. п.1)."""
    import sqlite3
    con = sqlite3.connect(db_path)
    con.row_factory = sqlite3.Row
    rows = con.execute("""
        SELECT i.activity_id, i.lap_type, i.duration_s, i.distance_m, i.avg_hr,
               a.date, a.type_guess
        FROM intervals i JOIN activities a ON a.activity_id = i.activity_id
        WHERE a.type_guess = 'interval' AND i.duration_s IS NOT NULL AND i.distance_m IS NOT NULL
    """).fetchall()
    con.close()
    active_types = {"INTERVAL_ACTIVE", "ACTIVE", "INTERVAL", "REPEAT", "WORK"}
    return [dict(r) for r in rows if (r["lap_type"] or "").upper() in active_types]


def collect_vdot_points(acts, laps):
    points = []  # (date_obj, vdot, source)
    for a in acts:
        if a["type_guess"] != "threshold":
            continue
        v = vdot_from_effort(a["distance_m"], a["duration_s"])
        if v is not None:
            points.append((datetime.date.fromisoformat(a["date"]), v, "порог (вся тренировка)"))
    for lap in laps:
        v = vdot_from_effort(lap["distance_m"], lap["duration_s"])
        if v is not None:
            points.append((datetime.date.fromisoformat(lap["date"]), v, "интервал (отрезок)"))
    points.sort(key=lambda p: p[0])
    return points


def rolling_max_by_date(points, day0, n_days, window_days):
    """Для каждого дня грид-а — максимум vdot среди точек за последние window_days
    (каузально, только назад) — устойчивая оценка "текущей формы", см. п.1."""
    daily_best = {}
    for d, v, _ in points:
        idx = (d - day0).days
        if 0 <= idx < n_days:
            daily_best[idx] = max(daily_best.get(idx, 0.0), v)
    out = [None] * n_days
    for t in range(n_days):
        lo = max(0, t - window_days + 1)
        vals = [daily_best[i] for i in range(lo, t + 1) if i in daily_best]
        if vals:
            out[t] = round(max(vals), 2)
    return out


