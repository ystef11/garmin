SUPERCOMP_WINDOW_D = 10
SUPERCOMP_MIN_PROMINENCE_RATIO = 0.20


def form_series(daily_load_axis, tau_adapt, tau_fatigue, k1, k2, baseline):
    fit_arr = gcf.recursive_convolution(daily_load_axis, tau_adapt)
    fat_arr = gcf.recursive_convolution(daily_load_axis, tau_fatigue)
    form = k1 * fit_arr - k2 * fat_arr
    return fit_arr, fat_arr, form


def find_supercompensation_peaks(form, window=SUPERCOMP_WINDOW_D,
                                  min_prominence_ratio=SUPERCOMP_MIN_PROMINENCE_RATIO):
    """v7: старая версия (окно ±3 дня, без порога значимости) отмечала пиком почти каждую
    точку — при дневном шуме локальный максимум в крохотном окне ±3 дня находится почти
    везде, из-за чего на графике «пики суперкомпенсации» были усыпаны точками через одну
    (см. скриншот пользователя). Теперь: (1) окно шире (±10 дней, это ближе к реальному
    масштабу цикла нагрузка→восстановление), (2) пик засчитывается только если он заметно
    (>=20%) выше локального минимума в этом же окне — иначе это не пик, а ровный шум."""
    n = len(form)
    peaks = [None] * n
    for i in range(n):
        if form[i] <= 0:
            continue
        lo, hi = max(0, i - window), min(n, i + window + 1)
        seg = form[lo:hi]
        local_max = max(seg)
        local_min = min(seg)
        if form[i] < local_max:
            continue
        prominence = local_max - local_min
        if prominence <= 0 or prominence < min_prominence_ratio * abs(local_max):
            continue
        peaks[i] = round(float(form[i]), 6)
    return peaks


