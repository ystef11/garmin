HR_ZONES = [
    ("Z1 восстановление (<60% HRR)", 0.0, 0.60),
    ("Z2 лёгкая (60-70% HRR)", 0.60, 0.70),
    ("Z3 темповая (70-80% HRR)", 0.70, 0.80),
    ("Z4 порог (80-90% HRR)", 0.80, 0.90),
    ("Z5 МПК (>=90% HRR)", 0.90, 10.0),
]


def hrr_zone(avg_hr, rest_hr, max_hr):
    if not avg_hr or not rest_hr or not max_hr or max_hr <= rest_hr:
        return None
    hrr = (avg_hr - rest_hr) / (max_hr - rest_hr)
    for label, lo, hi in HR_ZONES:
        if lo <= hrr < hi:
            return label
    return HR_ZONES[-1][0]


def month_label(d):
    return f"{d.year}-{d.month:02d}"


def monthly_pace_by_zone(acts, rest_hr, max_hr):
    """{zone_label: {month_label: темп_МИНУТ_НА_КМ (взвеш. по длительности)}} — в минутах
    на км (не в сырых секундах), чтобы читалось как привычный темп (напр. 5.62 = 5:37/км)."""
    buckets = {label: {} for label, _, _ in HR_ZONES}
    for a in acts:
        if not a.get("distance_m") or not a.get("duration_s") or not a.get("avg_hr"):
            continue
        zone = hrr_zone(a["avg_hr"], rest_hr, max_hr)
        if zone is None:
            continue
        pace_s = a["duration_s"] / (a["distance_m"] / 1000.0)  # сек/км
        ml = month_label(datetime.date.fromisoformat(a["date"]))
        acc = buckets[zone].setdefault(ml, [0.0, 0.0])  # [сумма(pace*dur), сумма(dur)]
        acc[0] += pace_s * a["duration_s"]
        acc[1] += a["duration_s"]
    result = {}
    for zone, months in buckets.items():
        result[zone] = {m: (v[0] / v[1]) / 60.0 for m, v in months.items() if v[1] > 0}  # -> мин/км
    return result


