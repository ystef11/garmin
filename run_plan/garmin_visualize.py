def acwr_series(daily_total_load, acute_days=7, chronic_days=28):
    weeks_in_chronic = chronic_days / acute_days
    n_days = len(daily_total_load)
    acwr = np.full(n_days, np.nan)
    for t in range(chronic_days - 1, n_days):
        acute = daily_total_load[t - acute_days + 1: t + 1].sum()
        chronic_weekly_avg = daily_total_load[t - chronic_days + 1: t + 1].sum() / weeks_in_chronic
        if chronic_weekly_avg > 1e-9:
            acwr[t] = acute / chronic_weekly_avg
    return acwr


