def build_week_grid(day0, n_days):
    """Группирует n_days подряд идущих дней (начиная с day0) по календарным неделям
    (Пн-Вс). Возвращает (week_starts: [date,...] по возрастанию, day_to_week: [int,...]
    длиной n_days — индекс недели для каждого дня)."""
    week_starts = []
    idx_map = {}
    day_to_week = [0] * n_days
    for i in range(n_days):
        d = day0 + datetime.timedelta(days=i)
        wk = d - datetime.timedelta(days=d.weekday())
        if wk not in idx_map:
            idx_map[wk] = len(week_starts)
            week_starts.append(wk)
        day_to_week[i] = idx_map[wk]
    return week_starts, day_to_week


def aggregate_weekly(values, day_to_week, n_weeks, agg="mean"):
    """values — список/массив длиной len(day_to_week); None/NaN игнорируются.
    agg: "mean" (сглаженный тренд, по умолчанию) или "max" (не терять короткие пики —
    используется для ACWR и "Пик суперкомпенсации", см. п.3/п.2 докстринга)."""
    buckets = [[] for _ in range(n_weeks)]
    for i, v in enumerate(values):
        if v is None:
            continue
        try:
            fv = float(v)
        except (TypeError, ValueError):
            continue
        if np.isnan(fv):
            continue
        buckets[day_to_week[i]].append(fv)
    out = []
    for b in buckets:
        if not b:
            out.append(None)
        elif agg == "max":
            out.append(max(b))
        else:
            out.append(sum(b) / len(b))
    return out


