def write_table(ws, headers, rows, date_col=None, note=None):
    """date_col — 1-based индекс колонки с датой. ВАЖНО (см. ЧТО ИСПРАВЛЕНО В v5 в докстринге
    модуля): дата пишется как ОБЫЧНАЯ ТЕКСТОВАЯ строка "ДД.ММ.ГГГГ", а не как объект
    datetime.date. Если писать настоящую дату, Excel формирует ссылку на категории графика
    как <c:numRef> (число) вместо <c:strRef> (текст) — в паре с обычной (не "датной") осью
    категорий это давало ПУСТУЮ подпись оси Х в реальном Excel (не в LibreOffice — тот
    рисовал нормально, поэтому баг не поймался на этапе проверки). Простой текст снимает
    вопрос полностью: тот же приём уже работал на листе "Темп_по_зонам" (там метка месяца
    всегда была строкой) — именно это единственный лист, на который не было жалоб."""
    for c, h in enumerate(headers, start=1):
        cell = ws.cell(row=1, column=c, value=h)
        cell.font = HEADER_FONT
        cell.fill = HEADER_FILL
        cell.alignment = Alignment(wrap_text=True, vertical="center")
    for r, row in enumerate(rows, start=2):
        for c, v in enumerate(row, start=1):
            if date_col and c == date_col and isinstance(v, (datetime.date, datetime.datetime)):
                v = v.strftime("%d.%m.%Y")
            ws.cell(row=r, column=c, value=v)
    ws.freeze_panes = "A2"
    for c in range(1, len(headers) + 1):
        ws.column_dimensions[get_column_letter(c)].width = 20
    if note:
        note_row = len(rows) + 3
        cell = ws.cell(row=note_row, column=1, value=note)
        cell.font = NOTE_FONT
        cell.alignment = Alignment(wrap_text=True)
        ws.merge_cells(start_row=note_row, start_column=1, end_row=note_row, end_column=min(len(headers), 4))


def add_trend_chart(ws, title, y_title, n_rows, series, anchor="H2", x_col=1, x_title="Неделя (начало)"):
    """series: [(col_idx, color, style)], style: "line" — обычная линия; "points" — только
    маркеры без соединяющей линии (для шумных разовых оценок вроде VDOT). Категорийная ось
    (НЕ DateAxis, см. докстринг модуля, ЧТО ИСПРАВЛЕНО В v3) — оси/связки НЕ подменяются
    вручную, используется штатная дефолтная пара axId, которая всегда самосогласована."""
    chart = LineChart()
    chart.title = title
    chart.y_axis.title = y_title
    chart.x_axis.title = x_title
    # ВАЖНО: у свежего openpyxl.LineChart() ОБЕ оси по умолчанию axPos="l" (левая) — это
    # не безопасный дефолт, а баг-ловушка: LibreOffice тихо перерисовывает ось категорий
    # снизу как ни в чём не бывало, а настоящий Excel располагает её буквально слева, из-за
    # чего подписи (в нашем случае — недели) с осью Х визуально не видны там, где ожидается
    # (баг всплыл только на реальном Excel пользователя, не в проверке через LibreOffice —
    # см. ЧТО ИСПРАВЛЕНО В v4 в докстринге модуля). Явно фиксируем нормальное расположение.
    chart.x_axis.axPos = "b"
    chart.y_axis.axPos = "l"
    # ВАЖНО (v7): без явного tickLblPos подписи оси не гарантированы — сама ось и её
    # заголовок ("Неделя (начало)" и т.п.) рисуются, но подписи-значения (даты/недели)
    # под ней — нет. LibreOffice в этом случае молча показывает подписи сам (используя
    # свой дефолт "nextTo"), а реальный Excel — нет, и получается пустая ось без дат при
    # полностью корректных axPos/strRef категориях (баг всплыл только на скриншоте из
    # реального Excel пользователя — см. ЧТО ИСПРАВЛЕНО В v7 в докстринге модуля).
    chart.x_axis.tickLblPos = "nextTo"
    chart.y_axis.tickLblPos = "nextTo"
    # ВАЖНО (v8): даже с верным axPos/strRef/tickLblPos подписи ВСЁ РАВНО не показались в
    # реальном Excel пользователя (скриншот после v7). Сравнила сырой XML нашего графика с
    # эталонным файлом от xlsxwriter (библиотека с проверенной совместимостью с настоящим
    # Excel, не только LibreOffice) — у openpyxl в файле не было: (1) кэша значений
    # <c:numCache>/<c:strCache> у серий и категорий (openpyxl пишет только ссылку на ячейки,
    # без кэша — Excel в такой комбинации не всегда сам считает подписи при открытии, а
    # LibreOffice — считает, отсюда разница), (2) <c:crosses>, (3) <c:auto>/<c:lblAlgn> на
    # оси категорий, (4) <c:crossBetween> на оси значений. Добавляем всё это явно — не
    # угадывая по одному тегу за раз, а приведя структуру к тому, что реально пишет
    # проверенная на Excel библиотека.
    chart.x_axis.crosses = "autoZero"
    chart.y_axis.crosses = "autoZero"
    chart.x_axis.auto = True
    chart.x_axis.lblAlgn = "ctr"
    chart.y_axis.crossBetween = "between"
    chart.width, chart.height = 26, 12
    try:
        chart.displayBlanksAs = "gap"
    except Exception:
        pass

    def _read_col(col_idx):
        return [ws.cell(row=r, column=col_idx).value for r in range(2, n_rows + 2)]

    cat_values = _read_col(x_col)
    cat_str_data = StrData(ptCount=len(cat_values),
                            pt=[StrVal(idx=i, v=str(v)) for i, v in enumerate(cat_values) if v is not None])

    for col, color, style in series:
        data = Reference(ws, min_col=col, min_row=1, max_row=n_rows + 1)
        chart.add_data(data, titles_from_data=True)
    # НЕ chart.set_categories() — тот метод ВСЕГДА оборачивает категории в <c:numRef> (см.
    # ЧТО ИСПРАВЛЕНО В v6 в докстринге модуля), даже когда сами ячейки текстовые. Категории
    # у нас текстовые (дата/месяц как строка) — строим ссылку явно как <c:strRef>, это
    # единственный способ надёжно получить подписи оси Х в реальном Excel.
    cat_range = f"'{ws.title}'!${get_column_letter(x_col)}${2}:${get_column_letter(x_col)}${n_rows + 1}"
    cat_source = AxDataSource(strRef=StrRef(f=cat_range, strCache=cat_str_data))
    for s in chart.series:
        s.cat = cat_source
    # Кэш значений для каждой серии — та же логика, что и для категорий выше.
    for s, (col, color, style) in zip(chart.series, series):
        vals = _read_col(col)
        num_data = NumData(formatCode="General", ptCount=len(vals),
                            pt=[NumVal(idx=i, v=float(v)) for i, v in enumerate(vals) if v is not None])
        s.val.numRef.numCache = num_data
    for s, (col, color, style) in zip(chart.series, series):
        if style == "points":
            s.marker = Marker(symbol="circle", size=6)
            s.marker.graphicalProperties.solidFill = color
            s.marker.graphicalProperties.line.noFill = True
            s.graphicalProperties.line.noFill = True
        else:
            s.marker = Marker(symbol="none")
            s.graphicalProperties.line.solidFill = color
            s.graphicalProperties.line.width = 20000
        s.smooth = False
    ws.add_chart(chart, anchor)
    return chart


